-- Run this in Supabase Dashboard > SQL Editor.
-- Each user can only read/write their own saved tutorial rows.
create table if not exists public.saved_tutorials (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tutorial_id text not null,
  created_at timestamptz not null default now(),
  unique (user_id, tutorial_id)
);

alter table public.saved_tutorials enable row level security;

create policy "Users can view their own saved tutorials"
on public.saved_tutorials for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can save their own tutorials"
on public.saved_tutorials for insert
to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can remove their own saved tutorials"
on public.saved_tutorials for delete
to authenticated
using ((select auth.uid()) = user_id);

create index if not exists saved_tutorials_user_id_idx
on public.saved_tutorials(user_id);
